#!/usr/bin/env python3
"""One-off generator: EF Core model snapshot -> baseline PostgreSQL DDL (fresh databases / CI only).
Existing databases are NOT touched by this file; the Node migration runner adopts them (see src/db/migrate.js).
Usage: gen-baseline-from-ef-snapshot.py <AppDbContextModelSnapshot.cs> <out.sql>"""
import re, sys, json
src = open(sys.argv[1], encoding='utf-8-sig').read()
VALUE = {'Guid','int','long','bool','DateTime','decimal','double','uint','short','TimeSpan','DateOnly','TimeOnly','float','byte','DateTimeOffset','ulong'}
# split into entity blocks
blocks = re.findall(r'modelBuilder\.Entity\("([^"]+)",\s*b\s*=>\s*\{(.*?)\n                \}\);', src, re.S)
ents = {}; fks = []
def q(s): return '"' + s + '"'
for name, body in blocks:
    e = ents.setdefault(name, dict(cols={}, order=[], pk=None, alt=[], idx=[], checks=[], table=None))
    # statements: split on ';'
    for st in [s.strip() for s in body.split(';')]:
        if not st: continue
        flat = re.sub(r'\s+', ' ', st)
        m = re.match(r'b\.Property<([^>]+(?:<[^>]*>)?)>\("(\w+)"\)(.*)', flat)
        if m:
            t, col, rest = m.groups()
            if 'HasColumnName("xmin")' in rest: continue
            ct = re.search(r'HasColumnType\("([^"]+)"\)', rest)
            req = '.IsRequired()' in rest
            nullable = t.endswith('?') or (t.rstrip('?') not in VALUE and not req)
            c = dict(type=ct.group(1) if ct else 'text', nullable=nullable and not req, identity=False)
            e['cols'][col] = c; e['order'].append(col); continue
        m = re.match(r'NpgsqlPropertyBuilderExtensions\.UseIdentityByDefaultColumn\(b\.Property<\w+>\("(\w+)"\)\)', flat)
        if m: e['cols'][m.group(1)]['identity'] = True; continue
        m = re.match(r'b\.HasKey\((.*?)\)$', flat)
        if m: e['pk'] = re.findall(r'"(\w+)"', m.group(1)); continue
        m = re.match(r'b\.HasAlternateKey\((.*?)\)$', flat)
        if m: e['alt'].append(re.findall(r'"(\w+)"', m.group(1))); continue
        m = re.match(r'b\.HasIndex\((.*?)\)(.*)$', flat)
        if m:
            cols = re.findall(r'"(\w+)"', m.group(1)); rest = m.group(2)
            nm = re.search(r'HasDatabaseName\("([^"]+)"\)', rest); fl = re.search(r'HasFilter\("((?:[^"\\]|\\.)*)"\)', rest)
            e['idx'].append(dict(cols=cols, unique='.IsUnique()' in rest, name=nm.group(1) if nm else None,
                                 filter=fl.group(1).replace('\\"', '"') if fl else None)); continue
        m = re.match(r'b\.ToTable\("(\w+)"', flat)
        if m:
            e['table'] = m.group(1)
            for ck in re.finditer(r't\.HasCheckConstraint\("(\w+)", "((?:[^"\\]|\\.)*)"\)', flat):
                e['checks'].append((ck.group(1), ck.group(2).replace('\\"', '"')))
            continue
        # relationships (second pass section)
        m = re.match(r'b\.HasOne\("([^"]+)", (?:null|"\w+")\) \.WithMany\((.*?)\) \.HasForeignKey\((.*?)\)(.*)', flat)
        if m:
            princ, _, fk, rest = m.groups()
            pk = re.search(r'HasPrincipalKey\((.*?)\)', rest)
            od = re.search(r'OnDelete\(DeleteBehavior\.(\w+)\)', rest)
            fks.append(dict(dep=name, princ=princ, cols=re.findall(r'"(\w+)"', fk),
                            pcols=re.findall(r'"(\w+)"', pk.group(1)) if pk else None, on=od.group(1) if od else 'ClientSetNull'))
# checks inside multi-line ToTable lambdas
for name, body in blocks:
    for ck in re.finditer(r'HasCheckConstraint\("(\w+)",\s*"((?:[^"\\]|\\.)*)"\)', body):
        e = ents[name]
        if ck.group(1) not in [c[0] for c in e['checks']]: e['checks'].append((ck.group(1), ck.group(2).replace('\\"', '"')))
out = ['-- GENERATED from the EF Core model snapshot by scripts/gen-baseline-from-ef-snapshot.py. Do not edit by hand.',
       '-- Applies only to EMPTY databases (CI / local). Existing databases are adopted by the runner without running this file.', '']
tables = {n: e for n, e in ents.items() if e['table']}
missing = [n for n, e in ents.items() if not e['table'] and e['cols']]
if missing: print('WARNING entities without table:', missing, file=sys.stderr)
for n, e in sorted(tables.items(), key=lambda kv: kv[1]['table']):
    lines = []
    for col in e['order']:
        c = e['cols'][col]
        ln = f'  {q(col)} {c["type"]}'
        if c['identity']: ln += ' GENERATED BY DEFAULT AS IDENTITY'
        if not c['nullable']: ln += ' NOT NULL'
        lines.append(ln)
    t = e['table']
    if e['pk']: lines.append(f'  CONSTRAINT {q("PK_"+t)} PRIMARY KEY ({", ".join(q(c) for c in e["pk"])})')
    for a in e['alt']: lines.append(f'  CONSTRAINT {q("AK_"+t+"_"+"_".join(a))} UNIQUE ({", ".join(q(c) for c in a)})')
    for nm, expr in e['checks']: lines.append(f'  CONSTRAINT {q(nm)} CHECK ({expr})')
    out.append(f'CREATE TABLE {q(t)} (\n' + ',\n'.join(lines) + '\n);\n')
for n, e in sorted(tables.items(), key=lambda kv: kv[1]['table']):
    t = e['table']
    for ix in e['idx']:
        nm = ix['name'] or (('UX_' if False else 'IX_') + t + '_' + '_'.join(ix['cols']))
        out.append(f'CREATE {"UNIQUE " if ix["unique"] else ""}INDEX {q(nm)} ON {q(t)} ({", ".join(q(c) for c in ix["cols"])})' + (f' WHERE {ix["filter"]}' if ix['filter'] else '') + ';')
out.append('')
act = {'Cascade': 'CASCADE', 'Restrict': 'RESTRICT', 'SetNull': 'SET NULL', 'NoAction': 'NO ACTION', 'ClientSetNull': 'RESTRICT'}
for f in fks:
    d = ents[f['dep']]; p = ents.get(f['princ'])
    if not d['table'] or not p or not p['table']: print('skip FK', f, file=sys.stderr); continue
    pcols = f['pcols'] or p['pk']
    nm = f'FK_{d["table"]}_{p["table"]}_{"_".join(f["cols"])}'[:63]
    out.append(f'ALTER TABLE {q(d["table"])} ADD CONSTRAINT {q(nm)} FOREIGN KEY ({", ".join(q(c) for c in f["cols"])}) REFERENCES {q(p["table"])} ({", ".join(q(c) for c in pcols)}) ON DELETE {act[f["on"]]};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
json.dump({e['table']: dict(columns={c: e['cols'][c] for c in e['order']}, pk=e['pk']) for e in tables.values()},
          open(sys.argv[2].replace('.sql', '.schema.json'), 'w'), indent=1)
print(len(tables), 'tables;', sum(len(e['idx']) for e in tables.values()), 'indexes;', len(fks), 'fks')
